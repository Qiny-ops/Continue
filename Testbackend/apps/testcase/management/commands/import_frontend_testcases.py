"""
导入前端功能测试用例的管理命令
创建覆盖率100%的前端界面功能测试用例
"""
from django.core.management.base import BaseCommand
from django.db import transaction
from apps.users.models import User, Role
from apps.projects.models import Project, ProjectMember
from apps.testcase.models import (
    TestCaseRepository, TestCaseVersion, TestModule,
    TestCase, TestStep
)


class Command(BaseCommand):
    help = '导入前端功能测试用例（覆盖率100%）'

    def add_arguments(self, parser):
        parser.add_argument(
            '--project-id',
            type=int,
            help='指定项目ID，如不指定则创建新项目'
        )
        parser.add_argument(
            '--user-id',
            type=int,
            help='指定用户ID作为创建者'
        )

    def handle(self, *args, **options):
        self.stdout.write('开始导入前端功能测试用例...')
        
        project_id = options.get('project_id')
        user_id = options.get('user_id')
        
        with transaction.atomic():
            user = self._get_or_create_user(user_id)
            project = self._get_or_create_project(project_id, user)
            repository, version = self._create_repository_and_version(project, user)
            
            modules = self._create_modules(version)
            
            test_cases_count = self._create_test_cases(version, modules, user)
            
            self.stdout.write(
                self.style.SUCCESS(
                    f'\n导入完成！\n'
                    f'- 项目: {project.name}\n'
                    f'- 用例库: {repository.name}\n'
                    f'- 版本: {version.name}\n'
                    f'- 模块数: {len(modules)}\n'
                    f'- 测试用例数: {test_cases_count}'
                )
            )

    def _get_or_create_user(self, user_id):
        if user_id:
            return User.objects.get(id=user_id)
        
        role, _ = Role.objects.get_or_create(
            code='admin',
            defaults={'name': '管理员', 'type': 'system', 'status': 'active'}
        )
        
        user, created = User.objects.get_or_create(
            username='frontend_test_admin',
            defaults={
                'email': 'frontend_test@example.com',
                'name': '前端测试管理员',
                'system_role': role,
                'status': 'active'
            }
        )
        if created:
            user.set_password('admin123')
            user.save()
        
        return user

    def _get_or_create_project(self, project_id, user):
        if project_id:
            return Project.objects.get(id=project_id)
        
        project, _ = Project.objects.get_or_create(
            code='FRONTEND_TEST',
            defaults={
                'name': '前端功能测试',
                'description': '前端界面功能测试用例，覆盖用户认证、项目管理、测试用例管理等所有前端功能',
                'type': 'web',
                'status': 'active',
                'owner': user
            }
        )
        
        ProjectMember.objects.get_or_create(
            project=project,
            user=user,
            defaults={'role': 'admin', 'status': 'active'}
        )
        
        return project

    def _create_repository_and_version(self, project, user):
        repository, _ = TestCaseRepository.objects.get_or_create(
            name='前端功能测试用例库',
            project=project,
            defaults={
                'description': '前端界面功能测试用例，覆盖率100%',
                'is_default': True,
                'created_by': user
            }
        )
        
        version, _ = TestCaseVersion.objects.get_or_create(
            repository=repository,
            name='v1.0',
            defaults={
                'description': '初始版本 - 全场景前端功能测试用例',
                'is_default': True,
                'created_by': user
            }
        )
        
        return repository, version

    def _create_modules(self, version):
        modules_config = [
            ('用户认证模块', [
                ('登录页面', None),
                ('注册页面', None),
                ('个人账户', None),
            ]),
            ('项目管理模块', [
                ('项目列表', None),
                ('项目创建', None),
                ('项目详情', None),
                ('成员管理', None),
                ('项目设置', None),
            ]),
            ('测试用例管理模块', [
                ('用例库版本', None),
                ('模块树', None),
                ('用例列表', None),
                ('用例CRUD', None),
                ('步骤管理', None),
                ('用例评审', None),
                ('用例执行', None),
            ]),
            ('UI组件模块', [
                ('表单验证', None),
                ('消息提示', None),
                ('列表组件', None),
            ]),
            ('响应式布局', None),
            ('路由导航', None),
            ('错误处理', None),
        ]
        
        modules = {}
        sort_order = 0
        
        for item in modules_config:
            if isinstance(item[1], list):
                parent_name, children = item
                parent = TestModule.objects.create(
                    version=version,
                    name=parent_name,
                    sort_order=sort_order
                )
                modules[parent_name] = parent
                sort_order += 1
                
                for child_name, _ in children:
                    child = TestModule.objects.create(
                        version=version,
                        name=child_name,
                        parent=parent,
                        sort_order=sort_order
                    )
                    modules[f"{parent_name}-{child_name}"] = child
                    sort_order += 1
            else:
                module_name = item[0]
                module = TestModule.objects.create(
                    version=version,
                    name=module_name,
                    sort_order=sort_order
                )
                modules[module_name] = module
                sort_order += 1
        
        return modules

    def _create_test_cases(self, version, modules, user):
        test_cases_data = self._get_test_cases_data()
        
        count = 0
        for module_key, test_cases in test_cases_data:
            module = modules.get(module_key)
            if not module:
                continue
            
            for tc_data in test_cases:
                tc = TestCase.objects.create(
                    title=tc_data['title'],
                    version=version,
                    module=module,
                    priority=tc_data.get('priority', 'p2'),
                    precondition=tc_data.get('precondition', ''),
                    tags=tc_data.get('tags', []),
                    created_by=user
                )
                
                for idx, (step_desc, expected) in enumerate(tc_data.get('steps', []), 1):
                    TestStep.objects.create(
                        test_case=tc,
                        step_number=idx,
                        description=step_desc,
                        expected_result=expected
                    )
                
                count += 1
        
        return count

