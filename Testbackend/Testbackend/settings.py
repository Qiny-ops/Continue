def check_production_settings():
    errors = []
    
    if not DEBUG:
        if not os.environ.get('DJANGO_SECRET_KEY'):
            errors.append("生产环境必须设置 DJANGO_SECRET_KEY 环境变量")
        
        if not os.environ.get('DJANGO_ALLOWED_HOSTS'):
            errors.append("生产环境必须设置 DJANGO_ALLOWED_HOSTS 环境变量")
        
        if ALLOWED_HOSTS == ['localhost', '127.0.0.1']:
            errors.append("生产环境 ALLOWED_HOSTS 不应仅包含 localhost 和 127.0.0.1")
        
        if not os.environ.get('DJANGO_DEBUG'):
            errors.append("生产环境应显式设置 DJANGO_DEBUG=False")
        
        if DATABASES['default']['ENGINE'] == 'django.db.backends.sqlite3':
            errors.append("生产环境不建议使用 SQLite 数据库")
    
    return errors


